@jit(nopython=True)
def simula_floresta_2(L, p, f, num_incendios):
    """
    Simula uma floresta com crescimento de árvores e incêndios periódicos.
    Compatível com Numba para maior desempenho, mantendo a funcionalidade original.
    """
    N = L * L  # Número total de nós na rede.
    viz = vizinhos(N)  # Calcula os vizinhos de cada nó da floresta.
    tam_incendios = np.zeros(num_incendios, dtype=np.int32)  # Armazena tamanhos dos incêndios.
    contador_incendios = 0  # Contador para o número de incêndios registrados.

    # Inicializa a floresta.
    floresta = np.zeros(shape=N, dtype=np.int8)

    while contador_incendios < num_incendios:
        # Crescimento de árvores.
        crescimento = np.random.rand(N) < p
        floresta[(floresta == 0) & crescimento] = 1

        # Queda de raio
        raio_caiu = False
        local_raio = -1
        if np.random.rand() < f:
            local_raio = np.random.randint(0, N)
            raio_caiu = True
            if floresta[local_raio] == 1:
                floresta[local_raio] = 2  # Vermelho para árvore atingida.
            else:
                floresta[local_raio] = 3  # Amarelo para local vazio.

        # Propagação do fogo
        if raio_caiu and floresta[local_raio] == 2:
            queimando = np.zeros(N, dtype=np.int8)  # Array para células em chamas.
            cluster = np.zeros(N, dtype=np.int8)  # Array para células do cluster.
            queimando[local_raio] = 1
            tamanho_cluster = 0

            while np.any(queimando == 1):  # Enquanto houver células queimando.
                for idx in range(N):
                    if queimando[idx] == 1:
                        queimando[idx] = 0
                        cluster[idx] = 1  # Marca como parte do cluster.
                        tamanho_cluster += 1
                        for v in viz[idx]:  # Propaga para os vizinhos.
                            if floresta[v] == 1:
                                floresta[v] = 4  # Laranja para árvores queimando no cluster.
                                queimando[v] = 1

            tam_incendios[contador_incendios] = tamanho_cluster
            contador_incendios += 1

        elif raio_caiu and floresta[local_raio] == 3:
            floresta[local_raio] = 0  # Limpa o local vazio atingido pelo raio.

        # Limpa árvores queimadas e reseta floresta.
        for i in range(N):
            if floresta[i] == 4:  # Laranja (árvore queimando no cluster).
                floresta[i] = 0
            elif floresta[i] == 2:  # Vermelho (árvore atingida diretamente).
                floresta[i] = 0

    return tam_incendios

def calcular_ccdf(tam_incendios, L):
    """
    Calcula a cCDF dos tamanhos de incêndios.
    """
    N = L * L
    tam_incendios = np.array(sorted(tam_incendios, reverse=True))

    # cCDF: Fração de incêndios maiores ou iguais a cada tamanho
    ccdf = np.arange(1, len(tam_incendios) + 1) / len(tam_incendios)

    # Tamanhos relativos
    tam_relativos = tam_incendios / N

    return ccdf, tam_relativos

def plotar_ccdf(tam_relativo, ccdf, L):
    """
    Plota a cCDF em função do tamanho relativo do incêndio.
    """
    plt.figure(figsize=(8, 6))
    plt.loglog(tam_relativo, ccdf, marker='o', linestyle='-', color='blue', label=f"L = {L}")
    plt.title("cCDF de Tamanhos Relativos de Incêndios")
    plt.xlabel("Tamanho Relativo do Incêndio (n / L²)")
    plt.ylabel("C(n)")
    plt.grid(True, which="both", linestyle="--", linewidth=0.5)
    plt.legend()
    plt.show()

