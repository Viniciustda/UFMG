@jit(nopython=True)
def vizinhos(N):
    """
    Calcula a tabela de vizinhos para uma grade 2D com condições de contorno periódicas.
    """
    L = int(np.sqrt(N))  # Calcula o tamanho de cada lado da rede, assumindo que é quadrada.
    viz = np.zeros((N, 4), dtype=np.int32)  # Inicializa a tabela de vizinhos (N nós, 4 vizinhos por nó).

    for k in range(N):  # Itera sobre cada nó da rede.
        # Vizinho à direita
        viz[k, 0] = k + 1
        if (k + 1) % L == 0:  # Se ultrapassou o limite direito, volta ao início da linha.
            viz[k, 0] = k + 1 - L

        # Vizinho abaixo
        viz[k, 1] = k + L
        if k >= (N - L):  # Se ultrapassou o limite inferior, conecta à linha superior.
            viz[k, 1] = k + L - N

        # Vizinho à esquerda
        viz[k, 2] = k - 1
        if k % L == 0:  # Se ultrapassou o limite esquerdo, conecta ao lado direito.
            viz[k, 2] = k + L - 1

        # Vizinho acima
        viz[k, 3] = k - L
        if k < L:  # Se ultrapassou o limite superior, conecta à linha inferior.
            viz[k, 3] = k + N - L

    return viz  # Retorna a tabela de vizinhos.

def simula_floresta(L, p, f, iteracoes, vizualizar):
    """
    Simula uma floresta com crescimento de árvores e incêndios periódicos.
    """
    N = L * L  # Número total de nós na rede.
    viz = vizinhos(N)  # Calcula os vizinhos de cada nó da floresta.
    tam_incendios = [] # Armazena tamanho dos incêndios.

    # Inicializa a floresta
    floresta = np.zeros(shape=N, dtype=np.int8)

    for t in range(iteracoes):
        # Estado inicial da iteração
        estado_inicial = floresta.copy()

        # Crescimento de árvores
        crescimento = np.random.rand(N) < p
        floresta[(floresta == 0) & crescimento] = 1

        # Queda de raio
        raio_caiu = False
        local_raio = -1
        if np.random.rand() < f:
            local_raio = np.random.randint(0, N)
            raio_caiu = True
            if floresta[local_raio] == 1:
                floresta[local_raio] = 2  # Vermelho para árvore atingida
            else:
                floresta[local_raio] = 3 # Amarelo para local vazio

        estado_raio = floresta.copy()

        # Propagação do fogo
        if raio_caiu and floresta[local_raio] == 2:
            queimando = [local_raio]
            cluster = []
            while queimando:
                idx = queimando.pop()
                if idx not in cluster:
                    cluster.append(idx)
                    for v in viz[idx]:
                        if floresta[v] == 1:
                            floresta[v] = 4
                            queimando.append(v)
            tam_incendios.append(len(cluster))

        elif raio_caiu and floresta[local_raio] == 3:
            floresta[local_raio] = 0

        # Estado do cluster queimado
        estado_cluster = floresta.copy()

        # Limpa arvores queimadas
        for i in range(N):
            if floresta[i] == 4:
                floresta[i] = 0
            elif floresta[i] == 2:
                floresta[i] = 0

        # Visualizações
        if vizualizar:
            visualizar_floresta(estado_inicial, estado_raio, estado_cluster, L, t, "Floresta")
            print("\n" + "=" * 80 + "\n")

    return tam_incendios

