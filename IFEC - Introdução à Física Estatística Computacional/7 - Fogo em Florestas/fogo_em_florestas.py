            # Gerar floresta aleatória com o mesmo número de árvores
            floresta_aleatoria = np.zeros(shape=N, dtype=np.int8)
            indices_arvores = np.random.choice(np.arange(N), size=num_arvores, replace=False)
            floresta_aleatoria[indices_arvores] = 1

            estado_inicial_aleatoria = floresta_aleatoria.copy()

            # Incêndio na floresta aleatória
