def ajustar_expoente(tam_relativos, ccdf):
    """
    Ajusta a inclinação da região linear no gráfico log-log da cCDF.
    """
    # Converte para log-log
    log_n = np.log(tam_relativos)
    log_c = np.log(ccdf)

    # Seleção da região linear (ajustar limites conforme necessário)
    mask = (log_n > -6) & (log_n < -1)  # Ajustar os limites
    log_n_linear = log_n[mask]
    log_c_linear = log_c[mask]

    # Realiza o ajuste linear: log(C(n)) = beta * log(n) + intercept
    beta, intercept = np.polyfit(log_n_linear, log_c_linear, 1)
    alpha = 1 - beta  # Calcula o expoente da lei de potência
    return alpha, beta, log_n_linear, log_c_linear, intercept

def plotar_ccdf_e_ajuste(tam_relativo, ccdf, alpha, beta, log_n_linear, intercept, L):
    """
    Plota a cCDF em escala log-log e inclui o ajuste linear calculado para os mesmos pontos do cCDF.
    """
    plt.figure(figsize=(8, 6))  # Tamanho consistente com a função plotar_ccdf

    # cCDF original
    plt.loglog(tam_relativo, ccdf, marker='o', linestyle='-', color='blue', label=f"L = {L}")

    # Ajuste linear calculado para os mesmos pontos do cCDF
    ajuste_y = np.exp(beta * np.log(tam_relativo) + intercept)  # Aplicando o ajuste linear diretamente aos dados
    plt.loglog(tam_relativo, ajuste_y, linestyle='--', color='red', label=f"Ajuste Linear ($\\alpha={alpha:.3f}$)")

    # Configurações do gráfico
    plt.title("cCDF de Tamanhos Relativos de Incêndios com Ajuste Linear")
    plt.xlabel("Tamanho Relativo do Incêndio (n / L²)")
    plt.ylabel("C(n)")
    plt.grid(True, which="both", linestyle="--", linewidth=0.5)
    plt.legend()
    plt.show()

